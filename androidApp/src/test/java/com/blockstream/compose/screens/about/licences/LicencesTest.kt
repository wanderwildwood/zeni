package com.blockstream.compose.screens.about.licences

import com.blockstream.compose.screens.about.SOURCE_URL
import com.blockstream.compose.screens.about.licenceFamilyFiles
import java.io.File
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The Licenses page's data as the build made it: the AboutLibraries plugin writes
 * build/generated/aboutLibraries/<variant>/res/raw/aboutlibraries.json before the unit tests
 * compile (it is part of the merged resources the R class comes from).
 */
class LicencesTest {
    private val json: File? = File("build/generated/aboutLibraries").walkTopDown()
        .filter { it.name == "aboutlibraries.json" }
        .sortedBy { if ("release" in it.path.lowercase()) 0 else 1 }
        .firstOrNull()

    private val generated by lazy { licenceComponentsFromJson(json!!.readText()) }

    private val res = File("../compose/src/commonMain/composeResources")

    private val data by lazy {
        LicencesData(
            "Bitcoin", SOURCE_URL, "GNU General Public License, version 3 only", generated,
            licenceFamilyFiles.map { (id, file) -> LicenceText(id, id, 0, File(res, file).readText()) },
        )
    }

    /** What must be on the page whatever else changes: group:artifact, or a config/libraries name. */
    private val EXPECTED = listOf(
        "com.google.guava:guava",
        "com.squareup.okio:okio",
        "com.google.protobuf:protobuf-java",
        "net.java.dev.jna:jna",
        "io.github.alexzhirkevich:qrose",
        "com.mudita:MMD",
        "Lato typeface",
        "Blockstream Green",
        "Blockstream GDK",
        "Tor",
    )

    @Test fun theBuildListedTheLibraries() {
        assertNotNull("no generated aboutlibraries.json: is the AboutLibraries plugin applied?", json)
        assertTrue(generated.size >= 50)
    }

    @Test fun theDataHasNoProblems() {
        assertEquals(emptyList<String>(), licencesProblems(data))
    }

    @Test fun everyExpectedComponentIsListed() {
        val missing = EXPECTED.filterNot { id -> generated.any { it.note?.startsWith("$id ") == true || it.name == id } }
        assertEquals(emptyList<String>(), missing)
    }

    /** MIT, BSD and ISC require the library's own notice: each such row carries its own text. */
    @Test fun permissiveLicencesCarryTheirOwnText() {
        val bare = generated.filter { c ->
            licenceFamilies(c.licence).any { it == "mit" || it == "bsd" } || "isc" in c.licence.lowercase()
        }.filter { c -> c.texts.none { it.content.orEmpty().contains("Copyright", ignoreCase = true) || it.content.orEmpty().contains("©") } }
        assertEquals(emptyList<String>(), bare.map { it.name })
    }

    @Test fun mmdIsShownAsMudita() {
        assertEquals("Mudita", generated.first { it.note?.startsWith("com.mudita:MMD ") == true }.author)
    }

    @Test fun androidXArtifactsHaveARowEach() {
        assertTrue(generated.count { it.note?.startsWith("androidx.") == true } > 20)
    }

    @Test fun theSourceLinkIsTheRepo() {
        assertEquals("https://github.com/wanderwildwood/zeni", SOURCE_URL)
    }

    @Test fun gplIsFirst() {
        assertEquals("gpl", orderedTexts(data.texts).first().id)
        assertTrue(licenceParagraphs(data.texts.first { it.id == "gpl" }.content!!).size > 10)
    }
}
